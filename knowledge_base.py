"""Validated visual vocabulary and local, explanation-aware retrieval.

The original supplied IDs remain canonical; retrieval does not need an online
embedding service. Only the selected context is sent to DeepSeek.
"""
import json
import math
import re
import unicodedata
from collections import Counter, defaultdict
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator
from storage import ROOT

KB_PATH = ROOT / "data" / "visual_knowledge.json"
SCHEMA_VERSION = "3.0"
GENERATOR_VERSION = "2026-10-15-v1"


def normalize(text):
    return re.sub(r"[\W_]+", "", unicodedata.normalize("NFKC", text).casefold())


def tokens(text):
    text = unicodedata.normalize("NFKC", text).casefold()
    result = re.findall(r"[a-z][a-z0-9-]*", text)
    for span in re.findall(r"[\u3400-\u9fff]+", text):
        if len(span) == 1:
            result.append(span)
        else:
            result.extend(span[i:i + 2] for i in range(len(span) - 1))
    return result


class Relation(BaseModel):
    model_config = ConfigDict(extra="forbid")
    term: str = Field(min_length=1)
    note: str = Field(min_length=8)
    term_id: str | None = None


class TermContent(BaseModel):
    """All prose in this schema is generated by DeepSeek, never templated locally."""
    model_config = ConfigDict(extra="forbid")
    id: str
    english_name: str = Field(min_length=1)
    aliases: list[str] = Field(default_factory=list)
    nature: str = Field(min_length=2)
    description: str = Field(min_length=35)
    visual_effect: str = Field(min_length=25)
    visual_cues: list[str] = Field(min_length=3, max_length=6)
    applicable_scenes: list[str] = Field(min_length=2, max_length=5)
    avoid_when: list[str] = Field(min_length=1, max_length=4)
    prompt_keywords: list[str] = Field(min_length=3, max_length=8)
    examples: list[str] = Field(min_length=1, max_length=2)
    confused_with: list[Relation] = Field(min_length=1, max_length=3)
    combinations: list[Relation] = Field(min_length=1, max_length=3)
    cautions: list[str] = Field(min_length=1, max_length=4)

    @field_validator("visual_cues", "applicable_scenes", "avoid_when", "prompt_keywords", "examples", "cautions")
    @classmethod
    def meaningful_items(cls, items):
        if any(not item.strip() or len(item.strip()) < 2 for item in items):
            raise ValueError("知识字段不得为空")
        if len(set(items)) != len(items):
            raise ValueError("同一字段内不得重复")
        return items


class KnowledgeTerm(TermContent):
    name: str
    category: str
    category_name: str
    source: str
    provenance: dict
    legacy_ids: list[str] = Field(default_factory=list)
    user_notes: str = ""
    status: Literal["active", "inactive"] = "active"


class KnowledgeBase:
    def __init__(self, terms, metadata=None):
        self.terms = terms
        self.metadata = metadata or {}
        self.by_id = {t["id"]: t for t in terms}
        self.postings = defaultdict(dict)
        self.identity_postings = defaultdict(list)
        self.lengths = []
        for index, term in enumerate(terms):
            identities = [term["name"], term.get("english_name", ""), *term.get("aliases", [])]
            for identity in identities:
                norm = normalize(identity)
                if norm:
                    self.identity_postings[norm].append(index)
            weighted = []
            for key, weight in (("name", 5), ("aliases", 4), ("english_name", 4), ("prompt_keywords", 3),
                                ("category_name", 1), ("description", 1), ("visual_effect", 1),
                                ("visual_cues", 2), ("applicable_scenes", 2)):
                value = term.get(key, "")
                weighted.extend(tokens(" ".join(value) if isinstance(value, list) else value) * weight)
            counts = Counter(weighted)
            self.lengths.append(len(weighted))
            for token, count in counts.items():
                self.postings[token][index] = count
        self.avg_length = sum(self.lengths) / max(1, len(terms))

    @classmethod
    def load(cls, path=KB_PATH):
        path = Path(path)
        if not path.exists():
            raise FileNotFoundError("知识库尚未构建，请运行 python build_knowledge.py")
        data = json.loads(path.read_text(encoding="utf-8"))
        if data.get("version") != SCHEMA_VERSION:
            raise ValueError("知识库版本不兼容，请重新构建")
        terms = [KnowledgeTerm.model_validate(t).model_dump() for t in data["terms"]]
        if len({t["id"] for t in terms}) != len(terms):
            raise ValueError("知识库含重复ID")
        return cls(terms, {k: v for k, v in data.items() if k != "terms"})

    def search(self, query, limit=12, category=None):
        categories = ({category} if isinstance(category, str) else set(category or []))
        def allowed(term):
            return not categories or term["category"] in categories
        if not query.strip():
            return [t for t in self.terms if t.get("status", "active") == "active"
                    and allowed(t)][:limit]
        scores = defaultdict(float)
        n = len(self.terms)
        for token in set(tokens(query)):
            posting = self.postings.get(token, {})
            idf = math.log(1 + (n - len(posting) + 0.5) / (len(posting) + 0.5))
            for index, tf in posting.items():
                denominator = tf + 1.2 * (0.25 + 0.75 * self.lengths[index] / max(1, self.avg_length))
                scores[index] += idf * tf * 2.2 / denominator
        norm_query = normalize(query)
        for identity, indices in self.identity_postings.items():
            if identity in norm_query or norm_query in identity:
                for index in indices:
                    scores[index] += 100 if identity == norm_query else 25 + min(15, len(identity))
        # A canonical name must outrank another term which happens to list it as an alias.
        for index in scores:
            if normalize(self.terms[index]["name"]) == norm_query:
                scores[index] += 80
        ranked = sorted(scores, key=lambda i: (-scores[i], self.terms[i]["id"]))
        return [self.terms[i] for i in ranked if self.terms[i].get("status", "active") == "active"
                and allowed(self.terms[i])][:limit]

    def prompt_material(self, term_ids):
        """Return exact, user-auditable knowledge fields for prompt drafting."""
        materials = []
        for identity in term_ids or []:
            term = self.by_id.get(identity)
            if not term:
                continue
            materials.append({
                "id": identity,
                "name": term["name"],
                "english_name": term["english_name"],
                "visual_effect": term["visual_effect"],
                "visual_cues": term["visual_cues"],
                "prompt_keywords": term["prompt_keywords"],
                "avoid_when": term["avoid_when"],
                "cautions": term["cautions"],
            })
        return materials

    def context(self, query, selected_ids=None, limit=10, max_chars=11000):
        selected = [self.by_id[i] for i in selected_ids or [] if i in self.by_id]
        selected_set = {t["id"] for t in selected}
        relevant = self.search(query, limit=limit)
        chosen = (selected + [t for t in relevant if t["id"] not in selected_set])[:limit]
        snippets, used, length = [], [], 0
        for term in chosen:
            compact = {
                "id": term["id"], "name": term["name"], "selected_by_user": term["id"] in selected_set,
                "definition": term["description"], "visual_cues": term["visual_cues"],
                "keywords": term["prompt_keywords"], "example": term["examples"][0],
                "avoid_when": term["avoid_when"], "cautions": term["cautions"],
                "confused_with": [{"term": r["term"], "note": r["note"]} for r in term["confused_with"]],
            }
            snippet = json.dumps(compact, ensure_ascii=False)
            addition = len(snippet) + (1 if snippets else 0)
            if length + addition > max_chars:
                continue
            snippets.append(snippet)
            used.append(term["id"])
            length += addition
        return "\n".join(snippets), used
